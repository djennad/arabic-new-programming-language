class محلل_البرنامج:
    def __init__(self, الأسطر):
        self.الأسطر = الأسطر
        self.الموضع = 0

    def انتهى(self):
        return self.الموضع >= len(self.الأسطر)

    def السطر_الحالي(self):
        if self.انتهى():
            return None
        return self.الأسطر[self.الموضع]

    def تقدم(self):
        س = self.السطر_الحالي()
        self.الموضع += 1
        return س

    def حلل_برنامج(self):
        return self.حلل_جمل(حتى=set())

    def حلل_جمل(self, حتى):
        الجمل = []
        while True:
            س = self.السطر_الحالي()
            if س is None:
                break
            _, الرموز = س
            if الرموز and الرموز[0].نوع == "كلمة" and الرموز[0].قيمة in حتى:
                break
            الجمل.append(self.حلل_جملة())
        return الجمل

    def حلل_كتلة(self):
        رقم_السطر, الرموز = self.السطر_الحالي() or (None, None)
        if الرموز is None or len(الرموز) != 1 or الرموز[0].قيمة != "بداية":
            raise خطأ_لغوي("متوقع 'بداية' لفتح كتلة", رقم_السطر)
        self.تقدم()
        الجمل = self.حلل_جمل(حتى={"نهاية"})
        رقم_سطر_النهاية, رموز_النهاية = self.السطر_الحالي() or (None, None)
        if رموز_النهاية is None or رموز_النهاية[0].قيمة != "نهاية":
            raise خطأ_لغوي("متوقع 'نهاية' لإغلاق الكتلة", رقم_سطر_النهاية)
        self.تقدم()
        return الجمل

    def حلل_جملة(self):
        رقم_السطر, الرموز = self.تقدم()
        الأول = الرموز[0]
        if الأول.نوع != "كلمة":
            raise خطأ_لغوي("يجب أن تبدأ الجملة بكلمة", رقم_السطر)
        الكلمة_الأولى = الأول.قيمة
        الباقي = الرموز[1:]

        if الكلمة_الأولى == "اطبع":
            return self._جملة_طبع(رقم_السطر, الباقي)
        if الكلمة_الأولى == "ادخل":
            return self._جملة_ادخال(رقم_السطر, الباقي)
        if الكلمة_الأولى == "اجعل":
            return self._جملة_اسناد(رقم_السطر, الباقي)
        if الكلمة_الأولى == "اذا":
            return self._جملة_اذا(رقم_السطر, الباقي)
        if الكلمة_الأولى == "طالما":
            return self._جملة_طالما(رقم_السطر, الباقي)
        if الكلمة_الأولى == "كرر":
            return self._جملة_كرر(رقم_السطر, الباقي)
        if الكلمة_الأولى == "دالة":
            return self._جملة_دالة(رقم_السطر, الباقي)
        if الكلمة_الأولى == "ارجع":
            expr = حلل_تعبير(الباقي, رقم_السطر, "قيمة الإرجاع") if الباقي else None
            return ("ارجع", expr, رقم_السطر)
        if الكلمة_الأولى == "نداء":
            return self._جملة_نداء(رقم_السطر, الباقي)
        if الكلمة_الأولى == "توقف":
            return ("توقف", رقم_السطر)
        if الكلمة_الأولى == "استمر":
            return ("استمر", رقم_السطر)

        raise خطأ_لغوي(f"جملة غير معروفة تبدأ بـ '{الكلمة_الأولى}'", رقم_السطر)

    def _جملة_طبع(self, رقم_السطر, الباقي):
        if not الباقي:
            raise خطأ_لغوي("اطبع تحتاج 'نص ...' أو 'قيمة ...' بعدها", رقم_السطر)
        if الباقي[0].قيمة == "نص":
            نص_المؤشر = مؤشر_الرموز(الباقي, رقم_السطر)
            expr = حلل_عامل(نص_المؤشر)
            نص_المؤشر.تحقق_من_الانتهاء("النص")
            return ("طبع_نص", expr, رقم_السطر)
        if الباقي[0].قيمة == "قيمة":
            expr = حلل_تعبير(الباقي[1:], رقم_السطر, "القيمة المطلوب طبعها")
            return ("طبع_قيمة", expr, رقم_السطر)
        raise خطأ_لغوي("اطبع تحتاج 'نص ...' أو 'قيمة ...' بعدها", رقم_السطر)

    def _جملة_ادخال(self, رقم_السطر, الباقي):
        if len(الباقي) != 1 or الباقي[0].نوع != "كلمة":
            raise خطأ_لغوي("ادخل تحتاج اسم متغير واحد بعدها", رقم_السطر)
        return ("ادخال", الباقي[0].قيمة, رقم_السطر)

    def _جملة_اسناد(self, رقم_السطر, الباقي):
        if len(الباقي) < 2 or الباقي[0].نوع != "كلمة" or الباقي[1].قيمة != "يساوي":
            raise خطأ_لغوي("اجعل تحتاج الصيغة: اجعل <متغير> يساوي <تعبير>", رقم_السطر)
        اسم_المتغير = الباقي[0].قيمة
        if اسم_المتغير in الكلمات_المحجوزة:
            raise خطأ_لغوي(f"لا يمكن استخدام '{اسم_المتغير}' اسمًا لمتغير", رقم_السطر)
        بقية_التعبير = الباقي[2:]
        if بقية_التعبير and بقية_التعبير[0].قيمة == "نداء":
            مؤشر = مؤشر_الرموز(بقية_التعبير, رقم_السطر)
            expr = حلل_عامل(مؤشر)
            مؤشر.تحقق_من_الانتهاء("نداء الدالة")
        else:
            expr = حلل_تعبير(بقية_التعبير, رقم_السطر, "التعبير المسنَد")
        return ("اسناد", اسم_المتغير, expr, رقم_السطر)

    def _جملة_اذا(self, رقم_السطر, الباقي):
        الشرط = حلل_تعبير(الباقي, رقم_السطر, "شرط اذا")
        كتلة_الاذا = self.حلل_كتلة()
        الفروع = [(الشرط, كتلة_الاذا)]
        كتلة_والا = None
        while True:
            س = self.السطر_الحالي()
            if س is None:
                break
            if س[1][0].قيمة != "والا":
                break
            رقم_والا, رموز_والا = self.تقدم()
            بقية_والا = رموز_والا[1:]
            if بقية_والا and بقية_والا[0].قيمة == "اذا":
                شرط_فرعي = حلل_تعبير(بقية_والا[1:], رقم_والا, "شرط والا اذا")
                كتلة_فرعية = self.حلل_كتلة()
                الفروع.append((شرط_فرعي, كتلة_فرعية))
                continue
            if بقية_والا:
                raise خطأ_لغوي("والا لا تأخذ أي كلمات بعدها إلا 'اذا'", رقم_والا)
            كتلة_والا = self.حلل_كتلة()
            break
        return ("اذا", الفروع, كتلة_والا, رقم_السطر)

    def _جملة_طالما(self, رقم_السطر, الباقي):
        الشرط = حلل_تعبير(الباقي, رقم_السطر, "شرط طالما")
        الكتلة = self.حلل_كتلة()
        return ("طالما", الشرط, الكتلة, رقم_السطر)

    def _جملة_كرر(self, رقم_السطر, الباقي):
        if len(الباقي) < 4 or الباقي[0].نوع != "كلمة" or الباقي[1].قيمة != "من":
            raise خطأ_لغوي(
                "كرر تحتاج الصيغة: كرر <متغير> من <تعبير> الى <تعبير> [بخطوة <تعبير>]",
                رقم_السطر,
            )
        اسم_المتغير = الباقي[0].قيمة
        بقية = الباقي[2:]
        فهرس_الى = next((i for i, ر in enumerate(بقية) if ر.قيمة == "الى"), None)
        if فهرس_الى is None:
            raise خطأ_لغوي("كرر تحتاج كلمة 'الى' لتحديد نهاية المدى", رقم_السطر)
        رموز_من = بقية[:فهرس_الى]
        بعد_الى = بقية[فهرس_الى + 1 :]
        فهرس_خطوة = next((i for i, ر in enumerate(بعد_الى) if ر.قيمة == "بخطوة"), None)
        if فهرس_خطوة is None:
            رموز_الى = بعد_الى
            رموز_خطوة = None
        else:
            رموز_الى = بعد_الى[:فهرس_خطوة]
            رموز_خطوة = بعد_الى[فهرس_خطوة + 1 :]
        expr_من = حلل_تعبير(رموز_من, رقم_السطر, "بداية المدى")
        expr_الى = حلل_تعبير(رموز_الى, رقم_السطر, "نهاية المدى")
        expr_خطوة = حلل_تعبير(رموز_خطوة, رقم_السطر, "الخطوة") if رموز_خطوة else None
        الكتلة = self.حلل_كتلة()
        return ("كرر", اسم_المتغير, expr_من, expr_الى, expr_خطوة, الكتلة, رقم_السطر)

    def _جملة_دالة(self, رقم_السطر, الباقي):
        if not الباقي or الباقي[0].نوع != "كلمة":
            raise خطأ_لغوي("دالة تحتاج اسمًا بعدها", رقم_السطر)
        الاسم = الباقي[0].قيمة
        المعطيات = []
        بقية = الباقي[1:]
        if بقية:
            if بقية[0].قيمة != "معطيات":
                raise خطأ_لغوي("متوقع 'معطيات' قبل أسماء المعطيات", رقم_السطر)
            for ر in بقية[1:]:
                if ر.نوع != "كلمة" or ر.قيمة in الكلمات_المحجوزة:
                    raise خطأ_لغوي(f"اسم معطى غير صالح: '{ر.قيمة}'", رقم_السطر)
                المعطيات.append(ر.قيمة)
        الكتلة = self.حلل_كتلة()
        return ("دالة", الاسم, المعطيات, الكتلة, رقم_السطر)

    def _جملة_نداء(self, رقم_السطر, الباقي):
        if not الباقي or الباقي[0].نوع != "كلمة":
            raise خطأ_لغوي("نداء تحتاج اسم دالة بعدها", رقم_السطر)
        الاسم = الباقي[0].قيمة
        المعطيات = حلل_قائمة_معطيات(الباقي[1:], رقم_السطر)
        return ("نداء_أمر", الاسم, المعطيات, رقم_السطر)


