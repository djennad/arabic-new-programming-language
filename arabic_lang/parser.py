الكلمات_المحجوزة = {
    "اطبع", "نص", "قيمة", "ادخل", "اجعل", "يساوي", "اذا", "والا", "طالما",
    "كرر", "من", "الى", "بخطوة", "بداية", "نهاية", "دالة", "معطيات", "ارجع",
    "نداء", "توقف", "استمر", "ملاحظة", "زائد", "ناقص", "في", "على", "باقي",
    "اكبر", "اصغر", "لا", "او", "و", "ليس", "صح", "خطأ", "فارغ",
}


def حلل_عامل(مؤشر, يسمح_بنداء=True):
    ر = مؤشر.الحالي()
    if ر is None:
        raise خطأ_لغوي("تعبير غير مكتمل", مؤشر.رقم_السطر)

    if ر.نوع == "رقم":
        مؤشر.تقدم()
        return ("عدد", ر.قيمة)

    كلمة = ر.قيمة

    if كلمة == "نص":
        مؤشر.تقدم()
        كلمات_النص = []
        while not مؤشر.انتهى():
            كلمات_النص.append(str(مؤشر.تقدم().قيمة))
        if not كلمات_النص:
            raise خطأ_لغوي("النص لا يمكن أن يكون فارغًا بعد كلمة 'نص'", مؤشر.رقم_السطر)
        return ("نص", " ".join(كلمات_النص))

    if كلمة == "صح":
        مؤشر.تقدم()
        return ("منطق", True)

    if كلمة == "خطأ":
        مؤشر.تقدم()
        return ("منطق", False)

    if كلمة == "فارغ":
        مؤشر.تقدم()
        return ("فارغ",)

    if كلمة == "نداء":
        if not يسمح_بنداء:
            raise خطأ_لغوي("لا يمكن نداء دالة داخل معطى دالة أخرى", مؤشر.رقم_السطر)
        مؤشر.تقدم()
        الاسم = مؤشر.استهلك_كلمة_حرة()
        رموز_الوسائط = مؤشر.الرموز[مؤشر.الموضع :]
        مؤشر.الموضع = len(مؤشر.الرموز)
        المعطيات = حلل_قائمة_معطيات(رموز_الوسائط, مؤشر.رقم_السطر)
        return ("نداء", الاسم, المعطيات)

    if كلمة in الكلمات_المحجوزة:
        raise خطأ_لغوي(f"لم يكن متوقعًا هنا: '{كلمة}'", مؤشر.رقم_السطر)

    مؤشر.تقدم()
    return ("متغير", كلمة)


def حلل_قائمة_معطيات(الرموز, رقم_السطر):
    """يقسّم قائمة رموز على كلمة الفصل 'و' ثم يحلل كل جزء كتعبير حسابي."""
    if not الرموز:
        return []
    المجموعات = [[]]
    for ر in الرموز:
        if ر.نوع == "كلمة" and ر.قيمة == "و":
            المجموعات.append([])
        else:
            المجموعات[-1].append(ر)
    المعطيات = []
    for مجموعة in المجموعات:
        if not مجموعة:
            raise خطأ_لغوي("معطى فارغ بين كلمتي فصل 'و'", رقم_السطر)
        مؤشر_فرعي = مؤشر_الرموز(مجموعة, رقم_السطر)
        المعطيات.append(حلل_جمع(مؤشر_فرعي, يسمح_بنداء=False))
        مؤشر_فرعي.تحقق_من_الانتهاء("المعطى")
    return المعطيات


def _استهلك_كلمة_حرة(self):
    ر = self.الحالي()
    if ر is None or ر.نوع != "كلمة" or ر.قيمة in الكلمات_المحجوزة:
        raise خطأ_لغوي("متوقع اسم (متغير أو دالة)", self.رقم_السطر)
    self.تقدم()
    return ر.قيمة


مؤشر_الرموز.استهلك_كلمة_حرة = _استهلك_كلمة_حرة


def حلل_حد(مؤشر, يسمح_بنداء=True):
    يسار = حلل_عامل(مؤشر, يسمح_بنداء)
    while مؤشر.كلمة_الحالي() in عمليات_الضرب:
        العملية = مؤشر.تقدم().قيمة
        يمين = حلل_عامل(مؤشر, يسمح_بنداء)
        يسار = ("عملية", العملية, يسار, يمين)
    return يسار


def حلل_جمع(مؤشر, يسمح_بنداء=True):
    يسار = حلل_حد(مؤشر, يسمح_بنداء)
    while مؤشر.كلمة_الحالي() in عمليات_الجمع:
        العملية = مؤشر.تقدم().قيمة
        يمين = حلل_حد(مؤشر, يسمح_بنداء)
        يسار = ("عملية", العملية, يسار, يمين)
    return يسار


def _حلل_عامل_مقارنة(مؤشر):
    if مؤشر.يطابق_كلمة("اكبر"):
        مؤشر.تقدم()
        مؤشر.استهلك_كلمة("من")
        if مؤشر.يطابق_كلمة("او"):
            مؤشر.تقدم()
            مؤشر.استهلك_كلمة("يساوي")
            return "اكبر_او_يساوي"
        return "اكبر"
    if مؤشر.يطابق_كلمة("اصغر"):
        مؤشر.تقدم()
        مؤشر.استهلك_كلمة("من")
        if مؤشر.يطابق_كلمة("او"):
            مؤشر.تقدم()
            مؤشر.استهلك_كلمة("يساوي")
            return "اصغر_او_يساوي"
        return "اصغر"
    if مؤشر.يطابق_كلمة("لا"):
        مؤشر.تقدم()
        مؤشر.استهلك_كلمة("يساوي")
        return "لا_يساوي"
    if مؤشر.يطابق_كلمة("يساوي"):
        مؤشر.تقدم()
        return "يساوي"
    return None


def حلل_مقارنة(مؤشر):
    يسار = حلل_جمع(مؤشر)
    العملية = _حلل_عامل_مقارنة(مؤشر)
    if العملية is None:
        return يسار
    يمين = حلل_جمع(مؤشر)
    return ("مقارنة", العملية, يسار, يمين)


def حلل_نفي(مؤشر):
    if مؤشر.يطابق_كلمة("ليس"):
        مؤشر.تقدم()
        return ("ليس", حلل_نفي(مؤشر))
    return حلل_مقارنة(مؤشر)


def حلل_و(مؤشر):
    يسار = حلل_نفي(مؤشر)
    while مؤشر.يطابق_كلمة("و"):
        مؤشر.تقدم()
        يمين = حلل_نفي(مؤشر)
        يسار = ("و", يسار, يمين)
    return يسار


def حلل_او(مؤشر):
    يسار = حلل_و(مؤشر)
    while مؤشر.يطابق_كلمة("او"):
        مؤشر.تقدم()
        يمين = حلل_و(مؤشر)
        يسار = ("او", يسار, يمين)
    return يسار


def حلل_تعبير(الرموز, رقم_السطر, وصف="التعبير"):
    if not الرموز:
        raise خطأ_لغوي(f"{وصف} ناقص", رقم_السطر)
    مؤشر = مؤشر_الرموز(الرموز, رقم_السطر)
    النتيجة = حلل_او(مؤشر)
    مؤشر.تحقق_من_الانتهاء(وصف)
    return النتيجة


