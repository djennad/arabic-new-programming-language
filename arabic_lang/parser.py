"""المحلل النحوي (parser): يبني شجرة تحليل من الأسطر والرموز."""

from .errors import خطأ_لغوي

# كلمات تُغلق تعبيرًا وتُنهي جملة (يمكن أن تبدأ خطوة رياضية جديدة أو تتوقف عندها)
عمليات_الجمع = {"زائد", "ناقص"}
عمليات_الضرب = {"في", "على", "باقي"}


class مؤشر_الرموز:
    def __init__(self, الرموز, رقم_السطر):
        self.الرموز = الرموز
        self.الموضع = 0
        self.رقم_السطر = رقم_السطر

    def انتهى(self):
        return self.الموضع >= len(self.الرموز)

    def الحالي(self):
        if self.انتهى():
            return None
        return self.الرموز[self.الموضع]

    def كلمة_الحالي(self):
        ر = self.الحالي()
        if ر is not None and ر.نوع == "كلمة":
            return ر.قيمة
        return None

    def تقدم(self):
        ر = self.الحالي()
        self.الموضع += 1
        return ر

    def يطابق_كلمة(self, *كلمات):
        return self.كلمة_الحالي() in كلمات

    def استهلك_كلمة(self, كلمة):
        if not self.يطابق_كلمة(كلمة):
            وجد = self.كلمة_الحالي() or (self.الحالي().قيمة if self.الحالي() else "نهاية السطر")
            raise خطأ_لغوي(f"متوقع الكلمة '{كلمة}' ولكن وُجد '{وجد}'", self.رقم_السطر)
        return self.تقدم()

    def تحقق_من_الانتهاء(self, وصف):
        if not self.انتهى():
            raise خطأ_لغوي(
                f"رموز زائدة بعد {وصف}: '{self.كلمة_الحالي() or self.الحالي().قيمة}'",
                self.رقم_السطر,
            )


