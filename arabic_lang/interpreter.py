"""المفسّر (interpreter): ينفّذ شجرة التحليل الناتجة عن المحلل النحوي."""

import math
import random

from .errors import خطأ_لغوي


class إشارة_ارجع(Exception):
    def __init__(self, قيمة):
        self.قيمة = قيمة


class إشارة_توقف(Exception):
    pass


class إشارة_استمر(Exception):
    pass


def صحيح_منطقيا(قيمة):
    if قيمة is None:
        return False
    if isinstance(قيمة, bool):
        return قيمة
    if isinstance(قيمة, (int, float)):
        return قيمة != 0
    if isinstance(قيمة, (str, list, dict)):
        return len(قيمة) > 0
    return True


def نسّق_للطباعة(قيمة):
    if قيمة is None:
        return "فارغ"
    if isinstance(قيمة, bool):
        return "صح" if قيمة else "خطأ"
    if isinstance(قيمة, float):
        if قيمة.is_integer():
            return str(int(قيمة))
        return str(قيمة)
    if isinstance(قيمة, list):
        return "[" + "، ".join(نسّق_للطباعة(عنصر) for عنصر in قيمة) + "]"
    if isinstance(قيمة, dict):
        الأزواج = (f"{نسّق_للطباعة(م)}: {نسّق_للطباعة(ق)}" for م, ق in قيمة.items())
        return "{" + "، ".join(الأزواج) + "}"
    return str(قيمة)


class بيئة:
    def __init__(self, أب=None):
        self.المتغيرات = {}
        self.الأب = أب

    def احصل(self, اسم, رقم_السطر):
        بيئة_حالية = self
        while بيئة_حالية is not None:
            if اسم in بيئة_حالية.المتغيرات:
                return بيئة_حالية.المتغيرات[اسم]
            بيئة_حالية = بيئة_حالية.الأب
        raise خطأ_لغوي(f"المتغير '{اسم}' غير معرّف", رقم_السطر)

    def عيّن(self, اسم, قيمة):
        self.المتغيرات[اسم] = قيمة


class مفسر:
    def __init__(self, مدخل=input, مخرج=print):
        self.المدخل = مدخل
        self.المخرج = مخرج
        self.الدوال = {}
        self.البيئة_العامة = بيئة()

    # -- تنفيذ البرنامج --------------------------------------------------

    def نفّذ_برنامج(self, الجمل):
        self._سجّل_الدوال(الجمل)
        self._نفّذ_جملا(الجمل, self.البيئة_العامة)

    def _سجّل_الدوال(self, الجمل):
        for جملة in الجمل:
            if جملة[0] == "دالة":
                _, الاسم, المعطيات, الكتلة, رقم_السطر = جملة
                if الاسم in self.الدوال:
                    raise خطأ_لغوي(f"الدالة '{الاسم}' معرّفة أكثر من مرة", رقم_السطر)
                self.الدوال[الاسم] = (المعطيات, الكتلة)

    def _نفّذ_جملا(self, الجمل, البيئة):
        for جملة in الجمل:
            self._نفّذ_جملة(جملة, البيئة)

    def _نفّذ_جملة(self, جملة, البيئة):
        النوع = جملة[0]

        if النوع == "طبع_نص":
            _, expr, رقم_السطر = جملة
            self.المخرج(نسّق_للطباعة(self._قيّم(expr, البيئة, رقم_السطر)))
            return

        if النوع == "طبع_قيمة":
            _, expr, رقم_السطر = جملة
            self.المخرج(نسّق_للطباعة(self._قيّم(expr, البيئة, رقم_السطر)))
            return

        if النوع == "ادخال":
            _, اسم_المتغير, رقم_السطر = جملة
            نص_مدخل = self.المدخل()
            البيئة.عيّن(اسم_المتغير, _حوّل_مدخلا(نص_مدخل))
            return

        if النوع == "اسناد":
            _, اسم_المتغير, expr, رقم_السطر = جملة
            البيئة.عيّن(اسم_المتغير, self._قيّم(expr, البيئة, رقم_السطر))
            return

        if النوع == "اسناد_عام":
            _, اسم_المتغير, expr, رقم_السطر = جملة
            self.البيئة_العامة.عيّن(اسم_المتغير, self._قيّم(expr, البيئة, رقم_السطر))
            return

        if النوع == "اسناد_عنصر":
            _, فهرس_ت, قائمة_ت, قيمة_ت, رقم_السطر = جملة
            الحاوية = self._قيّم(قائمة_ت, البيئة, رقم_السطر)
            المفتاح = self._قيّم(فهرس_ت, البيئة, رقم_السطر)
            self._اكتب_في_حاوية(الحاوية, المفتاح, self._قيّم(قيمة_ت, البيئة, رقم_السطر), رقم_السطر)
            return

        if النوع == "اضف":
            _, قيمة_ت, اسم_القائمة, رقم_السطر = جملة
            القائمة = البيئة.احصل(اسم_القائمة, رقم_السطر)
            self._تحقق_قائمة(القائمة, رقم_السطر)
            القائمة.append(self._قيّم(قيمة_ت, البيئة, رقم_السطر))
            return

        if النوع == "احذف":
            _, مفتاح_ت, حاوية_ت, رقم_السطر = جملة
            الحاوية = self._قيّم(حاوية_ت, البيئة, رقم_السطر)
            المفتاح = self._قيّم(مفتاح_ت, البيئة, رقم_السطر)
            if isinstance(الحاوية, list):
                del الحاوية[self._فهرس_قائمة(الحاوية, المفتاح, رقم_السطر)]
            elif isinstance(الحاوية, dict):
                if المفتاح not in الحاوية:
                    raise خطأ_لغوي("المفتاح غير موجود في القاموس", رقم_السطر)
                del الحاوية[المفتاح]
            else:
                raise خطأ_لغوي("احذف تحتاج قائمة أو قاموسًا", رقم_السطر)
            return

        if النوع == "لكل":
            _, اسم_المتغير, قائمة_ت, الكتلة, رقم_السطر = جملة
            القائمة = self._قيّم(قائمة_ت, البيئة, رقم_السطر)
            self._تحقق_قابل_للتكرار(القائمة, رقم_السطر)
            for عنصر in list(القائمة):
                البيئة.عيّن(اسم_المتغير, عنصر)
                try:
                    self._نفّذ_جملا(الكتلة, البيئة)
                except إشارة_توقف:
                    break
                except إشارة_استمر:
                    continue
            return

        if النوع in ("زد", "انقص"):
            _, اسم_المتغير, expr_المقدار, رقم_السطر = جملة
            القيمة_الحالية = البيئة.احصل(اسم_المتغير, رقم_السطر)
            المقدار = self._قيّم(expr_المقدار, البيئة, رقم_السطر)
            الجديدة = القيمة_الحالية + المقدار if النوع == "زد" else القيمة_الحالية - المقدار
            البيئة.عيّن(اسم_المتغير, الجديدة)
            return

        if النوع == "حاول":
            _, كتلة_المحاولة, اسم_متغير_الخطأ, كتلة_الامساك, رقم_السطر = جملة
            try:
                self._نفّذ_جملا(كتلة_المحاولة, البيئة)
            except خطأ_لغوي as خ:
                if اسم_متغير_الخطأ is not None:
                    البيئة.عيّن(اسم_متغير_الخطأ, خ.رسالة)
                self._نفّذ_جملا(كتلة_الامساك, البيئة)
            return

        if النوع == "اذا":
            _, الفروع, كتلة_والا, رقم_السطر = جملة
            for الشرط, كتلة in الفروع:
                if صحيح_منطقيا(self._قيّم(الشرط, البيئة, رقم_السطر)):
                    self._نفّذ_جملا(كتلة, البيئة)
                    return
            if كتلة_والا is not None:
                self._نفّذ_جملا(كتلة_والا, البيئة)
            return

        if النوع == "طالما":
            _, الشرط, الكتلة, رقم_السطر = جملة
            while صحيح_منطقيا(self._قيّم(الشرط, البيئة, رقم_السطر)):
                try:
                    self._نفّذ_جملا(الكتلة, البيئة)
                except إشارة_توقف:
                    break
                except إشارة_استمر:
                    continue
            return

        if النوع == "كرر":
            _, اسم_المتغير, expr_من, expr_الى, expr_خطوة, الكتلة, رقم_السطر = جملة
            بداية = self._قيّم(expr_من, البيئة, رقم_السطر)
            نهاية = self._قيّم(expr_الى, البيئة, رقم_السطر)
            خطوة = self._قيّم(expr_خطوة, البيئة, رقم_السطر) if expr_خطوة else (
                1 if نهاية >= بداية else -1
            )
            if خطوة == 0:
                raise خطأ_لغوي("لا يمكن أن تكون الخطوة صفرًا في 'كرر'", رقم_السطر)
            القيمة_الحالية = بداية
            while (خطوة > 0 and القيمة_الحالية <= نهاية) or (
                خطوة < 0 and القيمة_الحالية >= نهاية
            ):
                البيئة.عيّن(اسم_المتغير, القيمة_الحالية)
                try:
                    self._نفّذ_جملا(الكتلة, البيئة)
                except إشارة_توقف:
                    break
                except إشارة_استمر:
                    pass
                القيمة_الحالية = البيئة.احصل(اسم_المتغير, رقم_السطر) + خطوة
            return

        if النوع == "دالة":
            return  # سُجّلت مسبقًا قبل التنفيذ

        if النوع == "ارجع":
            _, expr, رقم_السطر = جملة
            قيمة = self._قيّم(expr, البيئة, رقم_السطر) if expr is not None else None
            raise إشارة_ارجع(قيمة)

        if النوع == "نداء_أمر":
            _, الاسم, المعطيات, رقم_السطر = جملة
            self._نادِ_دالة(الاسم, المعطيات, البيئة, رقم_السطر)
            return

        if النوع == "توقف":
            raise إشارة_توقف()

        if النوع == "استمر":
            raise إشارة_استمر()

        raise خطأ_لغوي(f"جملة غير مدعومة: {النوع}", جملة[-1])

    # -- تقييم التعبيرات ---------------------------------------------------

    def _نادِ_دالة(self, الاسم, معطيات_الاستدعاء, البيئة, رقم_السطر):
        if الاسم not in self.الدوال:
            if الاسم in الدوال_المدمجة:
                قيم = [self._قيّم(معطى, البيئة, رقم_السطر) for معطى in معطيات_الاستدعاء]
                return الدوال_المدمجة[الاسم](قيم, رقم_السطر)
            raise خطأ_لغوي(f"الدالة '{الاسم}' غير معرّفة", رقم_السطر)
        أسماء_المعطيات, الكتلة = self.الدوال[الاسم]
        if len(أسماء_المعطيات) != len(معطيات_الاستدعاء):
            raise خطأ_لغوي(
                f"الدالة '{الاسم}' تحتاج {len(أسماء_المعطيات)} معطى/معطيات "
                f"وتم تمرير {len(معطيات_الاستدعاء)}",
                رقم_السطر,
            )
        بيئة_الدالة = بيئة(self.البيئة_العامة)
        for اسم_معطى, تعبير_معطى in zip(أسماء_المعطيات, معطيات_الاستدعاء):
            بيئة_الدالة.عيّن(اسم_معطى, self._قيّم(تعبير_معطى, البيئة, رقم_السطر))
        try:
            self._نفّذ_جملا(الكتلة, بيئة_الدالة)
        except إشارة_ارجع as ر:
            return ر.قيمة
        return None

    def _قيّم(self, expr, البيئة, رقم_السطر):
        النوع = expr[0]

        if النوع == "عدد":
            return expr[1]
        if النوع == "نص":
            return expr[1]
        if النوع == "منطق":
            return expr[1]
        if النوع == "فارغ":
            return None
        if النوع == "متغير":
            return البيئة.احصل(expr[1], رقم_السطر)

        if النوع == "عملية":
            _, العملية, يسار_ت, يمين_ت = expr
            يسار = self._قيّم(يسار_ت, البيئة, رقم_السطر)
            يمين = self._قيّم(يمين_ت, البيئة, رقم_السطر)
            return _طبّق_عملية_حسابية(العملية, يسار, يمين, رقم_السطر)

        if النوع == "مقارنة":
            _, العملية, يسار_ت, يمين_ت = expr
            يسار = self._قيّم(يسار_ت, البيئة, رقم_السطر)
            يمين = self._قيّم(يمين_ت, البيئة, رقم_السطر)
            return _طبّق_مقارنة(العملية, يسار, يمين, رقم_السطر)

        if النوع == "و":
            _, يسار_ت, يمين_ت = expr
            if not صحيح_منطقيا(self._قيّم(يسار_ت, البيئة, رقم_السطر)):
                return False
            return صحيح_منطقيا(self._قيّم(يمين_ت, البيئة, رقم_السطر))

        if النوع == "او":
            _, يسار_ت, يمين_ت = expr
            if صحيح_منطقيا(self._قيّم(يسار_ت, البيئة, رقم_السطر)):
                return True
            return صحيح_منطقيا(self._قيّم(يمين_ت, البيئة, رقم_السطر))

        if النوع == "ليس":
            return not صحيح_منطقيا(self._قيّم(expr[1], البيئة, رقم_السطر))

        if النوع == "نداء":
            _, الاسم, المعطيات = expr
            return self._نادِ_دالة(الاسم, المعطيات, البيئة, رقم_السطر)

        if النوع == "سالب":
            القيمة = self._قيّم(expr[1], البيئة, رقم_السطر)
            if not isinstance(القيمة, (int, float)) or isinstance(القيمة, bool):
                raise خطأ_لغوي("'سالب' تحتاج عددًا", رقم_السطر)
            return -القيمة

        if النوع == "طول":
            القيمة = self._قيّم(expr[1], البيئة, رقم_السطر)
            if not isinstance(القيمة, (str, list, dict)):
                raise خطأ_لغوي("'طول' تحتاج نصًا أو قائمة أو قاموسًا", رقم_السطر)
            return len(القيمة)

        if النوع == "قائمة":
            _, العناصر = expr
            return [self._قيّم(عنصر, البيئة, رقم_السطر) for عنصر in العناصر]

        if النوع == "قاموس":
            _, الأزواج = expr
            نتيجة = {}
            for مفتاح_ت, قيمة_ت in الأزواج:
                مفتاح = self._قيّم(مفتاح_ت, البيئة, رقم_السطر)
                self._تحقق_مفتاح_صالح(مفتاح, رقم_السطر)
                نتيجة[مفتاح] = self._قيّم(قيمة_ت, البيئة, رقم_السطر)
            return نتيجة

        if النوع == "عنصر":
            _, فهرس_ت, قائمة_ت = expr
            الحاوية = self._قيّم(قائمة_ت, البيئة, رقم_السطر)
            المفتاح = self._قيّم(فهرس_ت, البيئة, رقم_السطر)
            return self._اقرأ_من_حاوية(الحاوية, المفتاح, رقم_السطر)

        raise خطأ_لغوي(f"تعبير غير مدعوم: {النوع}", رقم_السطر)

    @staticmethod
    def _تحقق_قائمة(قيمة, رقم_السطر):
        if not isinstance(قيمة, list):
            raise خطأ_لغوي("هذه القيمة ليست قائمة", رقم_السطر)

    @staticmethod
    def _تحقق_قابل_للتكرار(قيمة, رقم_السطر):
        if not isinstance(قيمة, (list, dict)):
            raise خطأ_لغوي("هذه القيمة ليست قائمة ولا قاموسًا", رقم_السطر)

    @staticmethod
    def _تحقق_مفتاح_صالح(مفتاح, رقم_السطر):
        if isinstance(مفتاح, (list, dict)):
            raise خطأ_لغوي("لا يمكن استخدام قائمة أو قاموس كمفتاح", رقم_السطر)

    @staticmethod
    def _فهرس_قائمة(القائمة, فهرس_من_واحد, رقم_السطر):
        if not isinstance(فهرس_من_واحد, (int, float)) or isinstance(فهرس_من_واحد, bool):
            raise خطأ_لغوي("فهرس العنصر يجب أن يكون عددًا", رقم_السطر)
        فهرس = int(فهرس_من_واحد) - 1
        if فهرس < 0 or فهرس >= len(القائمة):
            raise خطأ_لغوي(
                f"الفهرس {int(فهرس_من_واحد)} خارج حدود القائمة (طولها {len(القائمة)})",
                رقم_السطر,
            )
        return فهرس

    def _اقرأ_من_حاوية(self, الحاوية, المفتاح, رقم_السطر):
        if isinstance(الحاوية, list):
            return الحاوية[self._فهرس_قائمة(الحاوية, المفتاح, رقم_السطر)]
        if isinstance(الحاوية, dict):
            self._تحقق_مفتاح_صالح(المفتاح, رقم_السطر)
            if المفتاح not in الحاوية:
                raise خطأ_لغوي(f"المفتاح '{نسّق_للطباعة(المفتاح)}' غير موجود في القاموس", رقم_السطر)
            return الحاوية[المفتاح]
        raise خطأ_لغوي("هذه القيمة ليست قائمة ولا قاموسًا", رقم_السطر)

    def _اكتب_في_حاوية(self, الحاوية, المفتاح, قيمة, رقم_السطر):
        if isinstance(الحاوية, list):
            الحاوية[self._فهرس_قائمة(الحاوية, المفتاح, رقم_السطر)] = قيمة
            return
        if isinstance(الحاوية, dict):
            self._تحقق_مفتاح_صالح(المفتاح, رقم_السطر)
            الحاوية[المفتاح] = قيمة
            return
        raise خطأ_لغوي("هذه القيمة ليست قائمة ولا قاموسًا", رقم_السطر)


def _عدد_مطلوب(قيمة, اسم_الدالة, رقم_السطر):
    if not isinstance(قيمة, (int, float)) or isinstance(قيمة, bool):
        raise خطأ_لغوي(f"الدالة '{اسم_الدالة}' تحتاج عددًا", رقم_السطر)
    return قيمة


def _جذر_مدمج(قيم, رقم_السطر):
    if len(قيم) != 1:
        raise خطأ_لغوي("الدالة 'جذر' تحتاج معطى واحدًا", رقم_السطر)
    س = _عدد_مطلوب(قيم[0], "جذر", رقم_السطر)
    if س < 0:
        raise خطأ_لغوي("لا يمكن حساب جذر عدد سالب", رقم_السطر)
    return math.sqrt(س)


def _مطلق_مدمج(قيم, رقم_السطر):
    if len(قيم) != 1:
        raise خطأ_لغوي("الدالة 'مطلق' تحتاج معطى واحدًا", رقم_السطر)
    return abs(_عدد_مطلوب(قيم[0], "مطلق", رقم_السطر))


def _قوة_مدمجة(قيم, رقم_السطر):
    if len(قيم) != 2:
        raise خطأ_لغوي("الدالة 'قوة' تحتاج معطيين", رقم_السطر)
    الأساس = _عدد_مطلوب(قيم[0], "قوة", رقم_السطر)
    الأس = _عدد_مطلوب(قيم[1], "قوة", رقم_السطر)
    return الأساس ** الأس


def _تسوية_معطيات_عددية(قيم, اسم_الدالة, رقم_السطر):
    if len(قيم) == 1 and isinstance(قيم[0], list):
        قيم = قيم[0]
    if not قيم:
        raise خطأ_لغوي(f"الدالة '{اسم_الدالة}' تحتاج معطى واحدًا على الأقل", رقم_السطر)
    return [_عدد_مطلوب(ق, اسم_الدالة, رقم_السطر) for ق in قيم]


def _أعظم_مدمجة(قيم, رقم_السطر):
    return max(_تسوية_معطيات_عددية(قيم, "أعظم", رقم_السطر))


def _أصغر_مدمجة(قيم, رقم_السطر):
    return min(_تسوية_معطيات_عددية(قيم, "أصغر", رقم_السطر))


def _عشوائي_مدمجة(قيم, رقم_السطر):
    if len(قيم) != 2:
        raise خطأ_لغوي("الدالة 'عشوائي' تحتاج معطيين: من والى", رقم_السطر)
    من_ = int(_عدد_مطلوب(قيم[0], "عشوائي", رقم_السطر))
    الى_ = int(_عدد_مطلوب(قيم[1], "عشوائي", رقم_السطر))
    if من_ > الى_:
        من_, الى_ = الى_, من_
    return random.randint(من_, الى_)


def _رتب_مدمجة(قيم, رقم_السطر):
    if len(قيم) != 1 or not isinstance(قيم[0], list):
        raise خطأ_لغوي("الدالة 'رتب' تحتاج قائمة واحدة", رقم_السطر)
    try:
        return sorted(قيم[0])
    except TypeError as خطأ:
        raise خطأ_لغوي(f"لا يمكن ترتيب عناصر القائمة: {خطأ}", رقم_السطر)


def _اعكس_مدمجة(قيم, رقم_السطر):
    if len(قيم) != 1:
        raise خطأ_لغوي("الدالة 'اعكس' تحتاج معطى واحدًا (قائمة أو نص)", رقم_السطر)
    القيمة = قيم[0]
    if isinstance(القيمة, list):
        return list(reversed(القيمة))
    if isinstance(القيمة, str):
        return القيمة[::-1]
    raise خطأ_لغوي("الدالة 'اعكس' تحتاج قائمة أو نصًا", رقم_السطر)


