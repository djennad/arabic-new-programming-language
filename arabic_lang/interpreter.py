def _حوّل_مدخلا(نص_مدخل):
    نص_مدخل = نص_مدخل.strip()
    try:
        قيمة = float(نص_مدخل)
        if قيمة.is_integer():
            return int(قيمة)
        return قيمة
    except ValueError:
        return نص_مدخل


def _طبّق_عملية_حسابية(العملية, يسار, يمين, رقم_السطر):
    if isinstance(يسار, dict) or isinstance(يمين, dict):
        raise خطأ_لغوي("لا يمكن استخدام القواميس في العمليات الحسابية", رقم_السطر)
    if العملية == "زائد":
        if isinstance(يسار, list) and isinstance(يمين, list):
            return يسار + يمين
        if isinstance(يسار, str) or isinstance(يمين, str):
            return نسّق_للطباعة(يسار) + " " + نسّق_للطباعة(يمين)
        if isinstance(يسار, list) or isinstance(يمين, list):
            raise خطأ_لغوي("لا يمكن جمع قائمة مع قيمة ليست قائمة", رقم_السطر)
        return يسار + يمين
    if isinstance(يسار, str) or isinstance(يمين, str):
        raise خطأ_لغوي("لا يمكن استخدام النصوص مع 'ناقص' أو 'في' أو 'على' أو 'باقي'", رقم_السطر)
    if isinstance(يسار, list) or isinstance(يمين, list):
        raise خطأ_لغوي("لا يمكن استخدام القوائم مع 'ناقص' أو 'في' أو 'على' أو 'باقي'", رقم_السطر)
    if العملية == "ناقص":
        return يسار - يمين
    if العملية == "في":
        return يسار * يمين
    if العملية == "على":
        if يمين == 0:
            raise خطأ_لغوي("لا يمكن القسمة على صفر", رقم_السطر)
        return يسار / يمين
    if العملية == "باقي":
        if يمين == 0:
            raise خطأ_لغوي("لا يمكن أخذ الباقي بالقسمة على صفر", رقم_السطر)
        return يسار % يمين
    raise خطأ_لغوي(f"عملية غير معروفة: {العملية}", رقم_السطر)


def _طبّق_مقارنة(العملية, يسار, يمين, رقم_السطر):
    try:
        if العملية == "يساوي":
            return يسار == يمين
        if العملية == "لا_يساوي":
            return يسار != يمين
        if العملية == "اكبر":
            return يسار > يمين
        if العملية == "اصغر":
            return يسار < يمين
        if العملية == "اكبر_او_يساوي":
            return يسار >= يمين
        if العملية == "اصغر_او_يساوي":
            return يسار <= يمين
        if العملية == "يحتوي":
            if not isinstance(يسار, (list, dict, str)):
                raise خطأ_لغوي("'يحتوي' تحتاج قائمة أو قاموسًا أو نصًا على اليسار", رقم_السطر)
            return يمين in يسار
    except TypeError as خطأ:
        raise خطأ_لغوي(f"لا يمكن مقارنة القيم: {خطأ}", رقم_السطر)
    raise خطأ_لغوي(f"عملية مقارنة غير معروفة: {العملية}", رقم_السطر)
