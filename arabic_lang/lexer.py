"""المحلل اللفظي (lexer): يحوّل الشيفرة المصدرية إلى أسطر من الكلمات والأرقام.

قواعد اللغة: يُسمح فقط بالحروف العربية (لتكوين الكلمات) والأرقام 0-9
(لتكوين الأعداد)، مع السماح بنقطة عشرية واحدة داخل العدد مثل 1.8.
لا يوجد أي رمز آخر (لا أقواس ولا علامات ولا عوامل رياضية مكتوبة برموز).
"""

import re

from .errors import خطأ_لغوي

_نمط_الكلمة = re.compile(r"^[؀-ۿ]+$")
_نمط_الرقم = re.compile(r"^\d+(\.\d+)?$")
# يُسمح بأسماء لاتينية فقط داخل جملة 'استورد' (لأسماء مجلدات/ملفات حقيقية
# على القرص)، وليس في أي مكان آخر من اللغة.
_نمط_الكلمة_اللاتينية = re.compile(r"^[A-Za-z]+$")


class رمز:
    """Token: نوعه ('كلمة' أو 'رقم') وقيمته."""

    __slots__ = ("نوع", "قيمة", "سطر")

    def __init__(self, نوع, قيمة, سطر):
        self.نوع = نوع
        self.قيمة = قيمة
        self.سطر = سطر

    def __repr__(self):
        return f"رمز({self.نوع}, {self.قيمة!r})"


def _تحقق_من_الرمز(نص_الرمز, رقم_السطر, يسمح_بلاتينية=False):
    if _نمط_الرقم.match(نص_الرمز):
        قيمة = float(نص_الرمز)
        if قيمة.is_integer():
            قيمة = int(قيمة)
        return رمز("رقم", قيمة, رقم_السطر)
    if _نمط_الكلمة.match(نص_الرمز):
        return رمز("كلمة", نص_الرمز, رقم_السطر)
    if يسمح_بلاتينية and _نمط_الكلمة_اللاتينية.match(نص_الرمز):
        return رمز("كلمة", نص_الرمز, رقم_السطر)
    raise خطأ_لغوي(
        f"رمز غير مسموح به: '{نص_الرمز}' — يُسمح فقط بالحروف العربية والأرقام "
        "(مع نقطة عشرية اختيارية)",
        رقم_السطر,
    )


def حلل_الأسطر(المصدر):
    """يعيد قائمة من الأسطر، كل سطر هو (رقم_السطر, قائمة_الرموز).

    الأسطر الفارغة تُستبعد. كلمة 'ملاحظة' تبدأ تعليقًا حتى نهاية السطر،
    سواء وردت في بداية السطر أو بعد كود فعلي (تعليق نهاية سطر). الأسطر
    التي تبدأ بكلمة 'استورد' يُسمح فيها بأسماء لاتينية أيضًا (لمسارات
    الملفات/المجلدات الحقيقية على القرص).
    """

    الأسطر = []
    for رقم_السطر, نص_السطر in enumerate(المصدر.splitlines(), start=1):
        الكلمات = نص_السطر.split()
        if not الكلمات:
            continue
        if "ملاحظة" in الكلمات:
            الكلمات = الكلمات[: الكلمات.index("ملاحظة")]
        if not الكلمات:
            continue
        يسمح_بلاتينية = الكلمات[0] == "استورد"
        الرموز = [_تحقق_من_الرمز(ك, رقم_السطر, يسمح_بلاتينية) for ك in الكلمات]
        الأسطر.append((رقم_السطر, الرموز))
    return الأسطر
