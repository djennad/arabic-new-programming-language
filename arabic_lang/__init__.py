"""لغة برمجة عربية: تُكتب فقط بالكلمات العربية والأرقام (0-9، مع نقطة عشرية)."""

import os

from .errors import خطأ_لغوي
from .interpreter import مفسر
from .lexer import حلل_الأسطر
from .parser import حلل

__all__ = ["خطأ_لغوي", "شغّل_نص", "شغّل_ملف"]


def شغّل_نص(المصدر, مدخل=input, مخرج=print, مجلد_القاعدة=None):
    """يشغّل برنامجًا عربيًا من نص مصدري، ويعيد True عند النجاح."""
    الأسطر = حلل_الأسطر(المصدر)
    الشجرة = حلل(الأسطر)
    مفسر(مدخل=مدخل, مخرج=مخرج, مجلد_القاعدة=مجلد_القاعدة).نفّذ_برنامج(الشجرة)


def شغّل_ملف(المسار, مدخل=input, مخرج=print):
    with open(المسار, "r", encoding="utf-8") as ملف:
        المصدر = ملف.read()
    شغّل_نص(
        المصدر,
        مدخل=مدخل,
        مخرج=مخرج,
        مجلد_القاعدة=os.path.dirname(os.path.abspath(المسار)),
    )
