import io
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from arabic_lang import خطأ_لغوي, شغّل_نص


def شغّل(المصدر, مدخلات=None):
    مخرجات = []
    مصدر_المدخلات = iter(مدخلات or [])
    شغّل_نص(
        المصدر,
        مدخل=lambda: next(مصدر_المدخلات),
        مخرج=lambda س: مخرجات.append(str(س)),
    )
    return مخرجات


class اختبارات_أساسية(unittest.TestCase):
    def test_طباعة_نص(self):
        self.assertEqual(شغّل("اطبع نص مرحبا بالعالم"), ["مرحبا بالعالم"])

    def test_ادخال_وطباعة_قيمة(self):
        نتيجة = شغّل("ادخل ا\nاطبع قيمة ا", مدخلات=["15"])
        self.assertEqual(نتيجة, ["15"])

    def test_مثال_المستخدم_الكامل(self):
        برنامج = (
            "اطبع نص مرحبا بالعالم\n"
            "ادخل ا\n"
            "اطبع قيمة ا\n"
            "اذا ا اكبر من او يساوي 10\n"
            "بداية\n"
            "اطبع نص انه كبير\n"
            "نهاية\n"
        )
        self.assertEqual(
            شغّل(برنامج, مدخلات=["10"]),
            ["مرحبا بالعالم", "10", "انه كبير"],
        )
        self.assertEqual(
            شغّل(برنامج, مدخلات=["5"]),
            ["مرحبا بالعالم", "5"],
        )

    def test_اعداد_عشرية(self):
        برنامج = "اجعل س يساوي 1.8\nاجعل ص يساوي س في 3\nاطبع قيمة ص"
        self.assertEqual(شغّل(برنامج), ["5.4"])

    def test_عمليات_حسابية(self):
        برنامج = (
            "اطبع قيمة 2 زائد 3 في 4\n"
            "اطبع قيمة 10 ناقص 4 على 2\n"
            "اطبع قيمة 10 باقي 3\n"
        )
        self.assertEqual(شغّل(برنامج), ["14", "8", "1"])

    def test_القسمة_على_صفر(self):
        with self.assertRaises(خطأ_لغوي):
            شغّل("اطبع قيمة 1 على 0")

    def test_متغير_غير_معرف(self):
        with self.assertRaises(خطأ_لغوي):
            شغّل("اطبع قيمة لا_شيء")

    def test_رمز_غير_مسموح(self):
        with self.assertRaises(خطأ_لغوي):
            شغّل("اطبع قيمة 5+1")

    def test_والا(self):
        برنامج = (
            "اجعل ن يساوي 3\n"
            "اذا ن اكبر من 10\n"
            "بداية\nاطبع نص كبير\nنهاية\n"
            "والا\nبداية\nاطبع نص صغير\nنهاية\n"
        )
        self.assertEqual(شغّل(برنامج), ["صغير"])

    def test_والا_اذا_سلسلة(self):
        برنامج = (
            "اجعل الدرجة يساوي 75\n"
            "اذا الدرجة اكبر من او يساوي 90\nبداية\nاطبع نص ممتاز\nنهاية\n"
            "والا اذا الدرجة اكبر من او يساوي 60\nبداية\nاطبع نص جيد\nنهاية\n"
            "والا\nبداية\nاطبع نص راسب\nنهاية\n"
        )
        self.assertEqual(شغّل(برنامج), ["جيد"])

    def test_طالما(self):
        برنامج = (
            "اجعل ن يساوي 3\n"
            "طالما ن اكبر من 0\nبداية\nاطبع قيمة ن\nاجعل ن يساوي ن ناقص 1\nنهاية\n"
        )
        self.assertEqual(شغّل(برنامج), ["3", "2", "1"])

    def test_كرر(self):
        برنامج = "كرر ن من 1 الى 5\nبداية\nاطبع قيمة ن\nنهاية\n"
        self.assertEqual(شغّل(برنامج), ["1", "2", "3", "4", "5"])

    def test_كرر_بخطوة(self):
        برنامج = "كرر ن من 10 الى 0 بخطوة 0 ناقص 2\nبداية\nاطبع قيمة ن\nنهاية\n"
        self.assertEqual(شغّل(برنامج), ["10", "8", "6", "4", "2", "0"])

    def test_توقف_واستمر(self):
        برنامج = (
            "كرر ن من 1 الى 6\n"
            "بداية\n"
            "اذا ن يساوي 2\nبداية\nاستمر\nنهاية\n"
            "اذا ن يساوي 5\nبداية\nتوقف\nنهاية\n"
            "اطبع قيمة ن\n"
            "نهاية\n"
        )
        self.assertEqual(شغّل(برنامج), ["1", "3", "4"])

    def test_دالة_بمعطى_واحد(self):
        برنامج = (
            "دالة ضعف معطيات س\nبداية\nارجع س في 2\nنهاية\n"
            "اطبع قيمة نداء ضعف 21\n"
        )
        self.assertEqual(شغّل(برنامج), ["42"])

    def test_دالة_بمعطيين(self):
        برنامج = (
            "دالة اجمع معطيات س ص\nبداية\nارجع س زائد ص\nنهاية\n"
            "اطبع قيمة نداء اجمع 7 و 5\n"
        )
        self.assertEqual(شغّل(برنامج), ["12"])

    def test_دالة_تكرارية_فيبوناتشي(self):
        برنامج = (
            "دالة فيب معطيات ن\n"
            "بداية\n"
            "اذا ن اصغر من او يساوي 1\nبداية\nارجع ن\nنهاية\n"
            "اجعل أ يساوي نداء فيب ن ناقص 1\n"
            "اجعل ب يساوي نداء فيب ن ناقص 2\n"
            "ارجع أ زائد ب\n"
            "نهاية\n"
            "اطبع قيمة نداء فيب 10\n"
        )
        self.assertEqual(شغّل(برنامج), ["55"])

    def test_منطق_و_او_ليس(self):
        برنامج = (
            "اذا صح و ليس خطأ\nبداية\nاطبع نص نعم\nنهاية\n"
            "اذا خطأ او صح\nبداية\nاطبع نص ايضا صحيح\nنهاية\n"
        )
        self.assertEqual(شغّل(برنامج), ["نعم", "ايضا صحيح"])

    def test_دمج_النصوص(self):
        برنامج = (
            "اجعل الاسم يساوي نص احمد\n"
            "اجعل الرسالة يساوي نص مرحبا يا\n"
            "اطبع قيمة الرسالة زائد الاسم\n"
        )
        self.assertEqual(شغّل(برنامج), ["مرحبا يا احمد"])


if __name__ == "__main__":
    unittest.main()
